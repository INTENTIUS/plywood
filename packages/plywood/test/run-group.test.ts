/**
 * plywood#51: on Forgejo, a second merge cancelled the first merge's wave and
 * record jobs. Forgejo cancels the run in progress when a push starts a run of
 * a workflow that sets no workflow-level `concurrency:` (a job-level group does
 * not count), and chant writes the waves workflow and the pull request
 * workflow with none. plywood adds a group on Forgejo; GitHub cancels nothing
 * without one, and GitLab's jobs are not interruptible.
 */
import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { chantProduct, setChantProductForTests } from "../src/chant-product";
import { FALLBACK_EXIT } from "../src/exit-codes";
import { withRunGroup } from "../src/init/run-group";
import { runInit } from "../src/init";

afterEach(() => setChantProductForTests("reset"));

type Decision = { group: string; cancelsEarlierRuns: boolean };

/**
 * What Forgejo v16 does with a run of `text` for `event` (its
 * `ConfigureActionRunConcurrency` in services/actions/workflows.go): the group
 * is the workflow's `concurrency.group` evaluated, else one per ref, workflow
 * and event; `cancel-in-progress` unset cancels on a push or a pull request
 * sync, `true` cancels, `false` with a group queues behind runs in the group.
 */
function forgejoDecision(text: string, ctx: { event: string; sha: string; ref: string; runId: string }): Decision {
  const block = /^concurrency:\n((?:[ ]+.*\n)+)/m.exec(text)?.[1] ?? "";
  const field = (key: string): string | undefined => {
    const v = new RegExp(`^[ ]+${key}:[ ]*(.*)$`, "m").exec(block)?.[1]?.trim();
    return v === undefined ? undefined : v.replace(/^"(.*)"$/, "$1").replace(/^'(.*)'$/, "$1");
  };
  const evaluate = (s: string): string =>
    s.replace(/\$\{\{\s*(.*?)\s*\}\}/g, (_, expr: string) => {
      const pr = ctx.event === "pull_request";
      const e = expr.replace(/''/g, "'");
      if (e === "github.event_name") return ctx.event;
      if (e === "github.sha") return ctx.sha;
      if (e === "github.event_name == 'pull_request' && github.ref || github.run_id") return pr ? ctx.ref : ctx.runId;
      if (e === "github.event_name == 'pull_request'") return String(pr);
      throw new Error(`the test's evaluator does not know ${e}`);
    });
  const group = field("group") !== undefined ? evaluate(field("group")!) : `${ctx.ref}_workflow_${ctx.event}__auto`;
  const cancel = field("cancel-in-progress");
  const cancelValue = cancel === undefined ? undefined : evaluate(cancel) === "true";
  const unset = cancelValue === undefined;
  const cancels = unset ? ctx.event === "push" || ctx.event === "pull_request" : cancelValue;
  return { group, cancelsEarlierRuns: cancels };
}

/** Two merges: the same workflow, the same ref, two commits. */
function twoMerges(text: string, event = "push") {
  const a = forgejoDecision(text, { event, sha: "a".repeat(40), ref: "refs/heads/main", runId: "44" });
  const b = forgejoDecision(text, { event, sha: "b".repeat(40), ref: "refs/heads/main", runId: "49" });
  // A later run takes down the earlier one when it cancels in progress and the two share a group.
  return { a, b, firstRunCancelled: b.cancelsEarlierRuns && a.group === b.group };
}

const WAVES = "# Generated by chant\nname: pulumi-up\n\non:\n  push:\n    branches:\n      - main\n\njobs:\n  wave-1-dev:\n    steps: []\n";
const PR_LOOP =
  "name: chant-pr.shop.production\n\non:\n  pull_request: {}\n  push:\n    branches:\n      - main\n\nenv:\n  CHANT_ENV: production\n\njobs:\n  record:\n    if: github.event_name == 'push'\n    concurrency:\n      group: chant-record.shop.production\n      cancel-in-progress: false\n    steps: []\n";

describe("Forgejo's reading of a workflow with no group (the failure in plywood#51)", () => {
  it("cancels the first merge's run, also when only a job sets a group", () => {
    expect(twoMerges(WAVES).firstRunCancelled).toBe(true);
    expect(twoMerges(PR_LOOP).firstRunCancelled).toBe(true);
  });
});

describe("withRunGroup", () => {
  it("gives each merge's waves run a group of its own on Forgejo, with nothing cancelled", () => {
    const text = withRunGroup(WAVES, "forgejo", "commit");
    const { a, b, firstRunCancelled } = twoMerges(text);
    expect(a.group).not.toBe(b.group);
    expect(a.cancelsEarlierRuns).toBe(false);
    expect(firstRunCancelled).toBe(false);
    // A dispatch of the same commit twice queues behind the first, as one run at a time.
    const d1 = forgejoDecision(text, { event: "workflow_dispatch", sha: "a".repeat(40), ref: "refs/heads/main", runId: "1" });
    const d2 = forgejoDecision(text, { event: "workflow_dispatch", sha: "a".repeat(40), ref: "refs/heads/main", runId: "2" });
    expect(d1.group).toBe(d2.group);
    expect(d1.group).not.toBe(a.group);
  });

  it("keeps the record job's run from being cancelled by the next merge, and keeps a pull request's runs cancelling each other", () => {
    const text = withRunGroup(PR_LOOP, "forgejo", "pull-request");
    expect(twoMerges(text).firstRunCancelled).toBe(false);
    const pr = (runId: string) => forgejoDecision(text, { event: "pull_request", sha: runId, ref: "refs/pull/7/merge", runId });
    expect(pr("1").group).toBe(pr("2").group);
    expect(pr("2").cancelsEarlierRuns).toBe(true);
    // Comments never cancel anything and never wait for each other.
    const c = (runId: string) => forgejoDecision(text, { event: "issue_comment", sha: "x", ref: "refs/heads/main", runId });
    expect(c("1").group).not.toBe(c("2").group);
    expect(c("2").cancelsEarlierRuns).toBe(false);
  });

  it("puts the block before jobs: and leaves the rest of the file alone", () => {
    const text = withRunGroup(WAVES, "forgejo", "commit");
    expect(text.replace(/# Without a group[\s\S]*?cancel-in-progress: false\n\n/, "")).toBe(WAVES);
    expect(text.indexOf("\nconcurrency:\n")).toBeLessThan(text.indexOf("\njobs:\n"));
  });

  it("keeps a workflow-level group that is already there, and does not add a second", () => {
    const own = WAVES.replace("jobs:", "concurrency:\n  group: mine\n  cancel-in-progress: false\n\njobs:");
    expect(withRunGroup(own, "forgejo", "commit")).toBe(own);
    const once = withRunGroup(WAVES, "forgejo", "commit");
    expect(withRunGroup(once, "forgejo", "commit")).toBe(once);
  });

  it("leaves GitHub and GitLab files as they were", () => {
    expect(withRunGroup(WAVES, "github", "commit")).toBe(WAVES);
    expect(withRunGroup("stages: [a]\njobs-like:\n  script: x\n", "gitlab", "commit")).toBe("stages: [a]\njobs-like:\n  script: x\n");
  });
});

const real = await chantProduct();

/** `plywood init --forge` against the installed chant in a repository of two stacks; the text of every workflow it wrote. */
async function generated(forge: "github" | "forgejo" | "gitlab"): Promise<Record<string, string>> {
  setChantProductForTests("reset");
  const dir = mkdtempSync(join(tmpdir(), "plywood-run-group-"));
  mkdirSync(join(dir, ".git"));
  writeFileSync(join(dir, "Pulumi.yaml"), "name: shop\nruntime: nodejs\n");
  writeFileSync(join(dir, "Pulumi.dev.yaml"), "config: {}\n");
  writeFileSync(join(dir, "Pulumi.prod.yaml"), "config: {}\n");
  writeFileSync(join(dir, "package.json"), '{"name":"shop","private":true}\n');
  const err: string[] = [];
  // chant's in-process generator resolves its relative paths against the process's directory.
  const was = process.cwd();
  process.chdir(dir);
  const r = await runInit({ env: "production", bucketCheck: false, dryRun: false, yes: true, forge }, FALLBACK_EXIT, { cwd: dir, env: {}, out: () => {}, err: (s) => err.push(s) }).finally(() => process.chdir(was));
  expect(r.ok, JSON.stringify([r.notes, r.files, err])).toBe(true);
  const out: Record<string, string> = {};
  for (const sub of [".github/workflows", ".forgejo/workflows", "."]) {
    const d = join(dir, sub);
    if (!existsSync(d)) continue;
    for (const f of readdirSync(d)) if (/\.ya?ml$/.test(f) && f !== "plywood.yml" || sub !== "." && f === "plywood.yml") out[`${sub}/${f}`.replace("./", "")] = readFileSync(join(d, f), "utf8");
  }
  return out;
}

describe.runIf(real !== undefined)("the workflows chant writes for plywood's words", () => {
  it("on Forgejo: no merge's wave or record run is cancelled by the next merge", async () => {
    const files = await generated("forgejo");
    const waves = files[".forgejo/workflows/pulumi-up.yml"]!;
    const prLoop = files[".forgejo/workflows/plywood.yml"]!;
    expect(waves).toBeDefined();
    expect(prLoop).toContain("record:");
    expect(twoMerges(waves).firstRunCancelled).toBe(false);
    expect(twoMerges(prLoop).firstRunCancelled).toBe(false);
    // Every workflow that runs on a push to main has a group of its own for each commit or run.
    for (const [name, text] of Object.entries(files)) {
      if (!/^on:\n(?:.*\n)*?\s+push:/m.test(text) || name.endsWith("-plans.yml")) continue;
      expect(twoMerges(text).firstRunCancelled, name).toBe(false);
    }
  }, 60_000);

  it("on GitHub: no workflow-level group that could cancel a run, and none added", async () => {
    const files = await generated("github");
    for (const [name, text] of Object.entries(files)) {
      if (name.endsWith("-plans.yml")) continue; // runs on pull requests, where a newer push replacing the plan is wanted
      const block = /^concurrency:\n((?:[ ]+.*\n)+)/m.exec(text)?.[1] ?? "";
      expect(block, name).not.toMatch(/cancel-in-progress:\s*(true|'?\$\{\{)/);
    }
    expect(files[".github/workflows/pulumi-up.yml"]).not.toMatch(/^concurrency:/m);
    expect(files[".github/workflows/plywood.yml"]).not.toMatch(/^concurrency:/m);
  }, 60_000);

  it("on GitLab: no job is interruptible, so a newer pipeline never cancels a started one", async () => {
    const files = await generated("gitlab");
    expect(Object.keys(files).length).toBeGreaterThan(0);
    for (const [name, text] of Object.entries(files)) {
      expect(text, name).not.toMatch(/interruptible:\s*true/);
      expect(text, name).not.toMatch(/auto_cancel/);
    }
  }, 60_000);
});
